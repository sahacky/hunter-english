RULE_S08 = """**Инверсия условных: Had I known…, Were it not for…**
If исчезает, вспомогательный глагол выходит вперёд:
**Had I known**, I would have called = If I had known…
**Were it not for** you = If it weren't for you.
**Should you need** help = If you should need help (вежливое «вдруг понадобится»).
Разговорный дубль остаётся нормой: If I had known… — тоже верно.
Инверсия звучит формально и литературно."""

RULE_S09 = """**Пассив в формальном стиле.**
Безличный доклад: **It is believed/reported/thought that…** — считается/сообщается/полагают.
**He is said to be…** — говорят, он…; **She is expected to resign** — ожидается отставка.
Перфект/длительный пассив: **has been announced**, **is being looked into**.
**It cannot be ruled out** — исключить нельзя. **Little is known about…** — мало известно.
Это язык новостей и документов — учи блоками."""

